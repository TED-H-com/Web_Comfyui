"""Server-owned calibration catalog. Never accept paths, graphs or another owner's fixtures."""
import base64
import hashlib
import json
from pathlib import Path
from .contracts import fail, validate_bundle

class Materials:
    def __init__(self, web, root): self.web,self.root=web,Path(root)
    def catalog(self):
        try: return json.loads((self.root/'catalog.json').read_text())
        except (OSError,ValueError): return {'cases':[]}
    def authorize(self, owner, entry):
        if owner!=self.web.owner or owner!=entry.get('owner'):fail('parity_material_owner','此校準素材未授權給目前帳號')
        self.web._feature({'featureId':entry['feature']})
        return self.character(entry['character_id'])
    def character(self, character_id):
        if character_id.startswith('clipmode.character:'):
            runtime, actor = self.web.h._provider_runtime_actor()
            try:
                owned = runtime.store.get_owned_character(actor.user_id, character_id)
            except KeyError:
                fail('parity_material_owner','角色素材權限已變更')
            character = self.web.s.provider_character_studio_entry(owned)
        else:
            character = self.web.s.character_entry_for_generation(character_id,self.web.user,False)
        if not character:fail('parity_material_owner','角色素材權限已變更')
        return character
    def choices(self, feature):
        rows=[]
        for entry in self.catalog()['cases']:
            if entry['feature']!=feature:continue
            try:self.authorize(self.web.owner,entry)
            except Exception:continue
            rows.append({k:entry[k] for k in ('case_id','label','feature','ready','reason')})
        return rows
    def bundle(self, owner, request):
        cid=request.get('parity_case_id')
        if not isinstance(cid,str):fail('parity_case_required','請選擇已核准的校準素材')
        entry=next((c for c in self.catalog()['cases'] if c['case_id']==cid),None)
        if not entry or entry['feature']!=request.get('featureId'):fail('parity_case_required','校準案例與功能不符')
        self.authorize(owner,entry)
        if not entry['ready']:fail('parity_voice_gap','這名角色尚未提供自己的聲音')
        if request.get('characterId') and request['characterId']!=entry['character_id']:fail('parity_material_owner','角色與校準素材不符')
        # filename is generated by the freezer, never taken from a browser path.
        path=self.root/(entry['case_id']+'.json')
        b=json.loads(path.read_text());validate_bundle(b)
        if b['bundle_sha256']!=entry['bundle_sha256']:fail('bundle_changed','校準素材已變更')
        for item in b['inputs']+[b['character_original_image']]:
            source=Path(item.get('local_path') or item['path'])
            if not source.is_file() or source.stat().st_size!=item['bytes']:fail('input_hash_mismatch','校準素材已變更或移除')
        return b
    @staticmethod
    def read(item):
        raw=Path(item.get('local_path') or item['path']).read_bytes()
        if len(raw)!=item['bytes'] or hashlib.sha256(raw).hexdigest()!=item['sha256']:fail('input_hash_mismatch','校準素材已變更')
        return raw
    def __call__(self,owner,request):
        b=self.bundle(owner,request)
        self.read(b['character_original_image'])
        return b,{i['slot']:self.read(i) for i in b['inputs']}
    def local_request(self,bundle,files):
        import mimetypes
        from .persona import verify_persona
        character_id = bundle['request_context']['material_character']
        character = self.character(character_id)
        settings = dict(bundle['material_settings'])
        binding = {}
        if bundle['feature'] == 'voice-speak' and bundle.get('voice_selection'):
            fail('voice_selection_unsupported','此版本不支援借用聲音的校準案例')
        elif bundle['feature'] == 'voice-speak':
            capability = self.web.s.resolve_character_capability(character, 'voice-speak', 'voice-speak', 'voice-speak.persona.v1')
            settings = self.web.s.apply_character_capability_settings(character, capability, settings)
            verify_persona(bundle, settings['persona'])
            binding = {'action':capability['actionId'],'variantId':capability['variantId']}
        else:
            # Resolve the current server capability rather than browser metadata.
            capability = next((c for c in self.web.s.character_capabilities(character)
                if c['featureId']==bundle['feature'] and c['actionId']==bundle['feature'] and c.get('enabled')), None)
            if not capability:fail('parity_material_owner','角色功能未啟用')
            binding = {'action':capability['actionId'],'variantId':capability['variantId']}
        self.read(bundle['character_original_image'])
        return {'featureId':bundle['feature'],'characterId':character_id,**binding,'settings':settings,
            'files':{i['slot']:{'name':Path(i['name']).name,'dataUrl':'data:'+ (mimetypes.guess_type(i['name'])[0] or 'application/octet-stream')+';base64,'+base64.b64encode(files[i['slot']]).decode()} for i in bundle['inputs'] if i.get('node_id') is not None}}
